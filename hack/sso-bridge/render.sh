#!/usr/bin/env bash
# Renders the Keycloak sign-in bridge (sso_bridge.py, beside this script) into
# the packages whose open-source edition has no SSO of its own, and points each
# package's oauth2-proxy at it:
#
#   gateway -> <app>-oauth2-proxy (Keycloak login) -> <app>-sso-bridge -> <app>
#
# Run from the repo root after editing sso_bridge.py:
#   hack/sso-bridge/render.sh
set -euo pipefail
cd "$(dirname "$0")/../.."
SRC=hack/sso-bridge/sso_bridge.py
SUM=$(shasum -a 256 "$SRC" | cut -c1-16)

# render <package-dir> <app> <upstream-url> <credentials-secret> <email-key> <password-key> [api-key-key]
render() {
  local dir=$1 app=$2 upstream=$3 secret=$4 ekey=$5 pkey=$6 akey=${7:-}
  local out="$dir/manifests/sso-bridge.yaml"
  {
    cat <<EOF
# Keycloak sign-in for ${app}: its open-source edition sells SSO, so the
# oauth2-proxy (sso.yaml) authenticates the user and this bridge turns that
# identity into ${app}'s own session — the account is created on first visit and
# the user never sees ${app}'s login form. Platform admins (Keycloak group
# platform-admin) become ${app} administrators.
#
# GENERATED by hack/sso-bridge/render.sh from hack/sso-bridge/sso_bridge.py —
# edit those, not this file.
---
apiVersion: generators.external-secrets.io/v1alpha1
kind: Password
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "4"}
spec:
  length: 48
  digits: 8
  symbols: 0
  noUpper: false
  allowRepeat: true
---
# Minted ONCE: every account the bridge creates has a password derived from
# this key, so rotating it would lock those users out of ${app}.
apiVersion: external-secrets.io/v1
kind: ExternalSecret
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "4"}
spec:
  refreshInterval: '0'
  target:
    name: ${app}-sso-bridge
    creationPolicy: Owner
  dataFrom:
    - sourceRef:
        generatorRef:
          apiVersion: generators.external-secrets.io/v1alpha1
          kind: Password
          name: ${app}-sso-bridge
      rewrite:
        - transform:
            template: 'BRIDGE_SECRET'
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "4"}
  labels:
    app.kubernetes.io/name: ${app}-sso-bridge
    app.kubernetes.io/part-of: ${app}
data:
  sso_bridge.py: |
EOF
    sed 's/^/    /; s/^    $//' "$SRC"
    cat <<EOF
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "5"}
  labels:
    app.kubernetes.io/name: ${app}-sso-bridge
    app.kubernetes.io/part-of: ${app}
spec:
  progressDeadlineSeconds: 120
  replicas: 1
  selector:
    matchLabels:
      app: ${app}-sso-bridge
  template:
    metadata:
      labels:
        app: ${app}-sso-bridge
        app.kubernetes.io/part-of: ${app}
      annotations:
        adhar.io/bridge-checksum: "${SUM}"
    spec:
      enableServiceLinks: false
      automountServiceAccountToken: false
      securityContext:
        runAsNonRoot: true
        runAsUser: 65534
        runAsGroup: 65534
        seccompProfile: {type: RuntimeDefault}
      containers:
        - name: bridge
          image: docker.io/library/python:3.13-alpine
          command: ["python", "-I", "/bridge/sso_bridge.py"]
          env:
            - {name: MODE, value: ${app}}
            - {name: UPSTREAM, value: "${upstream}"}
            - {name: PYTHONDONTWRITEBYTECODE, value: "1"}
            - name: BRIDGE_SECRET
              valueFrom: {secretKeyRef: {name: ${app}-sso-bridge, key: BRIDGE_SECRET}}
            - name: ADMIN_EMAIL
              valueFrom: {secretKeyRef: {name: ${secret}, key: ${ekey}}}
            - name: ADMIN_PASSWORD
              valueFrom: {secretKeyRef: {name: ${secret}, key: ${pkey}}}
EOF
    if [ -n "$akey" ]; then
      cat <<EOF
            - name: API_KEY
              valueFrom: {secretKeyRef: {name: ${secret}, key: ${akey}}}
EOF
    fi
    cat <<EOF
          ports:
            - {name: http, containerPort: 8080}
          readinessProbe:
            httpGet: {path: /_bridge/healthz, port: 8080}
            periodSeconds: 10
            timeoutSeconds: 5
          livenessProbe:
            httpGet: {path: /_bridge/healthz, port: 8080}
            periodSeconds: 30
            timeoutSeconds: 10
          resources:
            requests: {cpu: 10m, memory: 32Mi}
            limits: {memory: 128Mi}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities: {drop: [ALL]}
          volumeMounts:
            - {name: bridge, mountPath: /bridge, readOnly: true}
      volumes:
        - name: bridge
          configMap: {name: ${app}-sso-bridge}
---
apiVersion: v1
kind: Service
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "5"}
  labels:
    app.kubernetes.io/name: ${app}-sso-bridge
    app.kubernetes.io/part-of: ${app}
spec:
  selector:
    app: ${app}-sso-bridge
  ports:
    - {name: http, port: 8080, targetPort: 8080}
---
# The bridge believes X-Forwarded-Email, so only the oauth2-proxy — which sets
# it from the Keycloak token and overwrites any client copy — may reach it.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: ${app}-sso-bridge
  namespace: adhar-system
  annotations: {argocd.argoproj.io/sync-wave: "5"}
spec:
  podSelector:
    matchLabels:
      app: ${app}-sso-bridge
  policyTypes: [Ingress]
  ingress:
    - from:
        - podSelector:
            matchLabels:
              app: ${app}-oauth2-proxy
      ports:
        - {protocol: TCP, port: 8080}
EOF
  } > "$out"
  # Repoint the proxy at the bridge. Only the upstream line: hack/gen-sso.sh
  # predates fixes later hand-applied to every sso.yaml (10s refresh,
  # progressDeadlineSeconds), so regenerating the whole file would revert them.
  local bridge="http://${app}-sso-bridge.adhar-system.svc.cluster.local:8080"
  sed -i.bak -E \
    -e "s#(--upstream=)http://[^ ]+#\\1${bridge}#" \
    -e "s#(the proxy forwards to )http://.*\$#\\1${bridge} (sso-bridge.yaml), which forwards to ${upstream}.#" \
    "$dir/manifests/sso.yaml"
  rm -f "$dir/manifests/sso.yaml.bak"
  echo "rendered $out"
}

render platform/stack/packages/data/metabase metabase \
  http://metabase.adhar-system.svc.cluster.local:80 metabase-admin-credentials username password
render platform/stack/packages/application/posthog posthog \
  http://posthog-web.adhar-system.svc.cluster.local:8000 posthog-console-credentials admin-email admin-password api-key
