#!/usr/bin/env bash
# Regenerates policy-under-test.yaml from manifests/volcano/kyverno-queue.yaml.
#
# The kyverno CLI panics on a policy with webhookConfiguration.matchConditions (1.19,
# pkg/validation/policy/validate.go asks a nil client for the server version), so the
# tests load the same policies without that block — as run-integrity/ does. Every
# rule's own preconditions hold the same username, and they are what these tests
# exercise; the webhook half is verified live (LIVE-PENDING).
# TestQueueBindingFixtureIsTheShippedPolicy holds the copy to the manifest.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "# GENERATED by generate-policy.sh from manifests/volcano/kyverno-queue.yaml, without matchConditions."
  awk '/^    matchConditions:$/{skip=1; next} skip && /^  rules:$/{skip=0} !skip' ../../manifests/volcano/kyverno-queue.yaml
} > policy-under-test.yaml
