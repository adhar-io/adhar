#!/usr/bin/env bash
# Regenerates values.yaml, resources.yaml and policy-under-test.yaml for the Volcano
# run-integrity suite (manifests/volcano/kyverno-run-integrity.yaml, FU-8).
#
# run-template.json is the composition's own run template for the design's
# partitioned example (testdata/batchjob-volcano/xr-partitioned.yaml: a manager task
# and four workers). TestVolcanoRunIntegrityFixtureIsTheComposedTemplate fails when
# the composition and this copy part; refresh it from the golden render
# (golden-volcano-gang.yaml, composed.run-template."template.yaml") and re-run this.
#
# The run every variant starts from is that template as a client creates it (cmd/batch
# buildRun: a name, the trigger label and env) and as Volcano v1.16's mutating webhook
# hands it on to validation: every task gains maxRetry 3 (mutate_job.go mutateSpec).
# Each variant changes one thing.
set -euo pipefail
cd "$(dirname "$0")"
admitted() { jq -c '.metadata.name="run" | .spec.tasks |= map(.maxRetry = (.maxRetry // 3))' run-template.json; }
variant() { # name, jq program
  admitted | jq -c --arg n "$1" "(.metadata.name=\$n) | ($2)"
  echo "---"
}
M='.spec.tasks[0].template.spec'
W='.spec.tasks[1].template.spec'
WC="${W}.containers[0]"
ALL='.spec.tasks[].template.spec.containers[0]'
{
  echo "# GENERATED by generate-resources.sh; each document is run-template.json as admitted, with one change."
  # Runs a client may start.
  variant run-ok '.'
  variant run-before-volcanos-webhook '.spec.tasks |= map(del(.maxRetry))'
  variant run-defaults-left-to-volcano 'del(.spec.maxRetry) | del(.spec.schedulerName) | .spec.tasks |= map(del(.minAvailable))'
  variant run-with-params "(${ALL}.env[] | select(.name==\"ADHAR_BATCH_PARAMS\").value) = \"{\\\"businessDate\\\":\\\"2026-11-03\\\"}\""
  variant run-restart "(${ALL}.env[] | select(.name==\"ADHAR_BATCH_TRIGGER\").value) = \"restart\" | ${ALL}.env += [{name:\"ADHAR_BATCH_RESTART_OF\",value:\"reconciler-09932cb3\"}] | .metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\" | .spec.tasks[].template.metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\""
  variant run-pinned-by-supply-chain "${ALL}.image |= . + \"@sha256:1111111111111111111111111111111111111111111111111111111111111111\""
  variant run-canonicalised-quantity "${WC}.resources.requests.memory=\"1.5Gi\" | ${WC}.resources.limits.memory=\"1.5Gi\" | ${M}.containers[0].resources.requests.cpu=\"0.5\""
  # Runs Kyverno must refuse.
  variant deny-image "${WC}.image=\"docker.io/library/busybox:1.36\""
  variant deny-manager-image "${M}.containers[0].image=\"docker.io/library/busybox:1.36\""
  variant deny-other-digest "${WC}.image=\"harbor-core.adhar-system.svc.cluster.local/library/other@sha256:1111111111111111111111111111111111111111111111111111111111111111\""
  variant deny-command "${WC}.command = [\"sh\",\"-c\",\"curl evil\"]"
  variant deny-args "${WC}.args = [\"--debug\"]"
  variant deny-extra-env "${WC}.env += [{name:\"EXTRA\",value:\"1\"}]"
  variant deny-changed-env "(${WC}.env[] | select(.name==\"ADHAR_BATCH_JOB\").value) = \"otherJob\""
  variant deny-db-secret "(${WC}.env[] | select(.name==\"SPRING_DATASOURCE_PASSWORD\").valueFrom.secretKeyRef.name) = \"other-db-app\""
  variant deny-envfrom "${WC}.envFrom = [{secretRef:{name:\"someone-elses\"}}]"
  variant deny-sidecar "${W}.containers += [{name:\"side\",image:\"docker.io/library/busybox:1.36\"}]"
  variant deny-init "${W}.initContainers = [{name:\"init\",image:\"docker.io/library/busybox:1.36\"}]"
  variant deny-service-account "${W}.serviceAccountName=\"default\""
  variant deny-volume "${W}.volumes += [{name:\"secret\",secret:{secretName:\"root-creds\"}}] | ${WC}.volumeMounts += [{name:\"secret\",mountPath:\"/s\"}]"
  variant deny-job-volume ".spec.volumes = [{mountPath:\"/data\",volumeClaimName:\"someone-elses\"}]"
  variant deny-tmp-swapped "(${W}.volumes[0]) = {name:\"tmp\",secret:{secretName:\"root-creds\"}}"
  variant deny-tmp-size "${W}.volumes[0].emptyDir.sizeLimit=\"100Gi\""
  variant deny-privileged "${WC}.securityContext.privileged=true"
  variant deny-host-network "${W}.hostNetwork=true"
  # A DRA claim reaches devices the BatchJob never asked for.
  variant deny-resource-claim "${W}.resourceClaims=[{name:\"gpu\",resourceClaimTemplateName:\"someone-elses-gpu\"}] | ${WC}.resources.claims=[{name:\"gpu\"}]"
  # Fields the view lists although none reaches a new image or identity today.
  variant deny-host-users "${W}.hostUsers=false"
  variant deny-volume-device "${WC}.volumeDevices=[{name:\"tmp\",devicePath:\"/dev/xvdf\"}]"
  variant deny-node-name "${W}.nodeName=\"worker-1\""
  variant deny-memory "${WC}.resources.requests.memory=\"64Gi\" | ${WC}.resources.limits.memory=\"64Gi\""
  variant deny-cpu "${WC}.resources.requests.cpu=\"32\""
  variant deny-cpu-limit "${WC}.resources.limits.cpu=\"32\""
  variant deny-extra-resource "${WC}.resources.requests[\"nvidia.com/gpu\"]=\"1\" | ${WC}.resources.limits[\"nvidia.com/gpu\"]=\"1\""
  variant deny-priority ".spec.priorityClassName=\"adhar-batch-volcano-critical\" | .spec.tasks[].template.spec.priorityClassName=\"adhar-batch-volcano-critical\""
  variant deny-pod-scheduler "${W}.schedulerName=\"default-scheduler\""
  variant deny-replicas ".spec.tasks[1].replicas=40 | .spec.tasks[1].minAvailable=40 | .spec.minAvailable=41"
  variant deny-min-available ".spec.minAvailable=1"
  variant deny-extra-task ".spec.tasks += [(.spec.tasks[1] | .name=\"rogue\" | .replicas=1 | .minAvailable=1)]"
  variant deny-task-policies ".spec.tasks[0] |= del(.policies)"
  variant deny-job-policies "del(.spec.policies)"
  variant deny-plugins ".spec.plugins.ssh = []"
  variant deny-max-retry ".spec.maxRetry=100"
  variant deny-ttl "del(.spec.ttlSecondsAfterFinished)"
  variant deny-deadline "${W}.activeDeadlineSeconds=9999999"
  variant deny-queue ".spec.queue=\"acme-payments-prod\""
  variant deny-scale-up-label ".metadata.labels[\"adhar.io/scale-up\"]=\"true\" | .spec.tasks[].template.metadata.labels[\"adhar.io/scale-up\"]=\"true\""
  variant deny-dropped-identity "del(.spec.tasks[1].template.metadata.labels[\"adhar.io/team\"])"
  variant deny-evictable "del(.spec.tasks[1].template.metadata.annotations[\"cluster-autoscaler.kubernetes.io/safe-to-evict\"])"
  # Volcano's scheduling knobs: volcano.sh/preemptable "false" makes a run immune to
  # reclaim (A2.4), on the Job (copied to the PodGroup and pods) or on a task template.
  variant deny-not-preemptable '.metadata.annotations["volcano.sh/preemptable"]="false"'
  variant deny-task-not-preemptable '.spec.tasks[1].template.metadata.annotations["volcano.sh/preemptable"]="false"'
  variant deny-task-not-preemptable-label '.spec.tasks[1].template.metadata.labels["volcano.sh/preemptable"]="false"'
  variant deny-job-not-preemptable-label '.metadata.labels["volcano.sh/preemptable"]="false"'
  variant deny-revocable-zone '.metadata.annotations["volcano.sh/revocable-zone"]="*"'
  # The forged label: claiming to be the schedule skips nothing.
  variant deny-forged-schedule-label ".metadata.labels[\"adhar.io/batch-trigger\"]=\"schedule\" | .spec.tasks[].template.metadata.labels[\"adhar.io/batch-trigger\"]=\"schedule\" | ${WC}.image=\"docker.io/library/busybox:1.36\""
  # A template that does not exist is no template to match.
  variant deny-no-template '.metadata.labels["adhar.io/batch-job"]="no-such-job" | .spec.tasks[].template.metadata.labels["adhar.io/batch-job"]="no-such-job"'
  # For pinned-template/: a template that itself names a digest admits that digest only.
  variant pinned-template-run "${ALL}.image |= . + \"@sha256:1111111111111111111111111111111111111111111111111111111111111111\""
  variant pinned-template-other-digest "${ALL}.image |= . + \"@sha256:2222222222222222222222222222222222222222222222222222222222222222\""
  # The e2e suite's forged Volcano run (tests/e2e/batch volcano_gang.go SyntheticGang):
  # a one-member busybox gang on dev's own leaf, claiming the application.
  variant deny-forged-gang '{apiVersion: .apiVersion, kind: .kind, metadata: {name: "deny-forged-gang", namespace: "dev", labels: {"adhar.io/batch-job": "reconciler", "adhar.io/workload": "batch"}},
    spec: {schedulerName: "volcano", queue: .spec.queue, priorityClassName: "adhar-batch-volcano", minAvailable: 1, maxRetry: 0, ttlSecondsAfterFinished: 600,
      tasks: [{name: "member", replicas: 1, maxRetry: 3, minAvailable: 1, template: {spec: {schedulerName: "volcano", priorityClassName: "adhar-batch-volcano",
        restartPolicy: "Never", activeDeadlineSeconds: 3600, containers: [{name: "member", image: "docker.io/library/busybox:1.36", command: ["sleep", "60"]}]}}}]}}'
} > resources.yaml

# What the policy reads from the cluster, mocked: ConfigMap <batch-job>-run's
# template.yaml. JSON is YAML, so parse_yaml reads run-template.json as it is.
{
  echo "# GENERATED by generate-resources.sh from run-template.json (the composed run template)."
  echo "apiVersion: cli.kyverno.io/v1alpha1"
  echo "kind: Values"
  echo "metadata:"
  echo "  name: volcano-run-integrity"
  echo "policies:"
  echo "  - name: adhar-batch-run-integrity-volcano"
  echo "    rules:"
  echo "      - name: a-volcano-run-matches-its-template"
  echo "        values:"
  echo "          templateYaml: $(jq -c . run-template.json | jq -Rs 'rtrimstr("\n")')"
} > values.yaml

# pinned-template/: the same template with every image pinned to a digest.
{
  echo "# GENERATED by generate-resources.sh from run-template.json, every image pinned to a digest."
  echo "apiVersion: cli.kyverno.io/v1alpha1"
  echo "kind: Values"
  echo "metadata:"
  echo "  name: volcano-run-integrity-pinned-template"
  echo "policies:"
  echo "  - name: adhar-batch-run-integrity-volcano"
  echo "    rules:"
  echo "      - name: a-volcano-run-matches-its-template"
  echo "        values:"
  echo "          templateYaml: $(jq -c '.spec.tasks[].template.spec.containers[].image |= . + "@sha256:1111111111111111111111111111111111111111111111111111111111111111"' run-template.json | jq -Rs 'rtrimstr("\n")')"
} > pinned-template/values.yaml

# The kyverno CLI panics on a policy with webhookConfiguration.matchConditions (1.19,
# see ../run-integrity/generate-resources.sh), so the tests load the shipped file
# without those blocks. TestVolcanoRunIntegrityFixtureIsTheShippedPolicy holds the copy
# to the manifest.
{
  echo "# GENERATED by generate-resources.sh from manifests/volcano/kyverno-run-integrity.yaml, without matchConditions."
  awk '/^    matchConditions:$/{skip=1; next} skip && /^  rules:$/{skip=0} !skip' ../../manifests/volcano/kyverno-run-integrity.yaml
} > policy-under-test.yaml
