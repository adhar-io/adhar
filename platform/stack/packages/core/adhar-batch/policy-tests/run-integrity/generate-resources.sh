#!/usr/bin/env bash
# Regenerates resources.yaml from job-as-admitted.json: the Job a client creates from
# the run template of testdata/batchjob/xr-ondemand.yaml, exactly as the API server
# hands it to admission (`kubectl create --dry-run=server` on Kubernetes 1.37), so
# every default the policy must tolerate is in it. Each variant changes one thing.
set -euo pipefail
cd "$(dirname "$0")"
variant() { # name, jq program
  jq -c --arg n "$1" "(.metadata.name=\$n) | ($2)" job-as-admitted.json
  echo "---"
}
C='.spec.template.spec.containers[0]'
{
  echo "# GENERATED by generate-resources.sh; each document is job-as-admitted.json with one change."
  # Runs a client may start.
  variant run-ok '.'
  variant run-with-params "(${C}.env[] | select(.name==\"ADHAR_BATCH_PARAMS\").value) = \"{\\\"businessDate\\\":\\\"2026-11-03\\\"}\""
  variant run-restart "(${C}.env[] | select(.name==\"ADHAR_BATCH_TRIGGER\").value) = \"restart\" | ${C}.env += [{name:\"ADHAR_BATCH_RESTART_OF\",value:\"importer-09932cb3\"}] | .metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\""
  variant run-pinned-by-supply-chain "${C}.image = \"harbor-core.adhar-system.svc.cluster.local/library/reconciler:1.0.0@sha256:1111111111111111111111111111111111111111111111111111111111111111\""
  variant run-canonicalised-quantity "${C}.resources.requests.memory=\"1.5Gi\" | ${C}.resources.limits.memory=\"1.5Gi\""
  variant run-suspended ".spec.suspend=true"
  # Runs Kyverno must refuse.
  variant deny-image "${C}.image=\"docker.io/library/busybox:1.36\""
  variant deny-other-digest "${C}.image=\"harbor-core.adhar-system.svc.cluster.local/library/other@sha256:1111111111111111111111111111111111111111111111111111111111111111\""
  variant deny-extra-env "${C}.env += [{name:\"EXTRA\",value:\"1\"}]"
  variant deny-changed-env "(${C}.env[] | select(.name==\"ADHAR_BATCH_JOB\").value) = \"otherJob\""
  variant deny-db-secret "(${C}.env[] | select(.name==\"SPRING_DATASOURCE_PASSWORD\").valueFrom.secretKeyRef.name) = \"other-db-app\""
  variant deny-removed-env "${C}.env |= map(select(.name!=\"OTEL_SERVICE_NAME\"))"
  variant deny-envfrom "${C}.envFrom = [{secretRef:{name:\"someone-elses\"}}]"
  variant deny-command "${C}.command = [\"sh\",\"-c\",\"curl evil\"]"
  variant deny-args "${C}.args = [\"--debug\"]"
  variant deny-sidecar ".spec.template.spec.containers += [{name:\"side\",image:\"docker.io/library/busybox:1.36\"}]"
  variant deny-init ".spec.template.spec.initContainers = [{name:\"init\",image:\"docker.io/library/busybox:1.36\"}]"
  variant deny-service-account ".spec.template.spec.serviceAccountName=\"default\" | .spec.template.spec.serviceAccount=\"default\""
  variant deny-volume ".spec.template.spec.volumes += [{name:\"secret\",secret:{secretName:\"root-creds\"}}] | ${C}.volumeMounts += [{name:\"secret\",mountPath:\"/s\"}]"
  variant deny-tmp-swapped "(.spec.template.spec.volumes[0]) = {name:\"tmp\",secret:{secretName:\"root-creds\"}}"
  variant deny-tmp-size ".spec.template.spec.volumes[0].emptyDir.sizeLimit=\"100Gi\""
  variant deny-privileged "${C}.securityContext.privileged=true"
  variant deny-host-network ".spec.template.spec.hostNetwork=true"
  # A DRA claim reaches devices the BatchJob never asked for.
  variant deny-resource-claim ".spec.template.spec.resourceClaims=[{name:\"gpu\",resourceClaimTemplateName:\"someone-elses-gpu\"}] | ${C}.resources.claims=[{name:\"gpu\"}]"
  # Fields the view lists although none reaches a new image or identity today.
  variant deny-host-users ".spec.template.spec.hostUsers=false"
  variant deny-volume-device "${C}.volumeDevices=[{name:\"tmp\",devicePath:\"/dev/xvdf\"}]"
  variant deny-node-name ".spec.template.spec.nodeName=\"worker-1\""
  variant deny-memory "${C}.resources.requests.memory=\"64Gi\" | ${C}.resources.limits.memory=\"64Gi\""
  variant deny-cpu "${C}.resources.requests.cpu=\"32\""
  variant deny-cpu-limit "${C}.resources.limits.cpu=\"32\""
  variant deny-extra-resource "${C}.resources.requests[\"nvidia.com/gpu\"]=\"1\" | ${C}.resources.limits[\"nvidia.com/gpu\"]=\"1\""
  variant deny-priority ".spec.template.spec.priorityClassName=\"adhar-node-bound\""
  variant deny-parallelism ".spec.parallelism=8 | .spec.completions=8"
  variant deny-deadline ".spec.activeDeadlineSeconds=9999999"
  variant deny-backoff ".spec.backoffLimit=100"
  variant deny-failure-policy "del(.spec.podFailurePolicy)"
  variant deny-manual-selector ".spec.manualSelector=true"
  variant deny-scale-up-label ".metadata.labels[\"adhar.io/scale-up\"]=\"true\" | .spec.template.metadata.labels[\"adhar.io/scale-up\"]=\"true\""
  variant deny-dropped-identity "del(.spec.template.metadata.labels[\"adhar.io/team\"])"
  variant deny-evictable "del(.spec.template.metadata.annotations[\"cluster-autoscaler.kubernetes.io/safe-to-evict\"])"
  # The forged label: claiming to be the schedule skips nothing.
  variant deny-forged-schedule-label ".metadata.labels[\"adhar.io/batch-trigger\"]=\"schedule\" | .spec.template.metadata.labels[\"adhar.io/batch-trigger\"]=\"schedule\" | ${C}.image=\"docker.io/library/busybox:1.36\""
  # A template that does not exist is no template to match.
  variant deny-no-template '.metadata.labels["adhar.io/batch-job"]="no-such-job" | .spec.template.metadata.labels["adhar.io/batch-job"]="no-such-job"'
} > resources.yaml

# The kyverno CLI panics on a policy with webhookConfiguration.matchConditions (1.19.1,
# pkg/validation/policy/validate.go asks a nil client for the server version), so the
# tests load the same policy without that block. The rule's own preconditions hold the
# same username list, and they are what these tests exercise. The webhook half is
# verified live (LIVE-PENDING). TestBatchRunIntegrityFixtureIsTheShippedPolicy holds the
# copy to the manifest.
{
  echo "# GENERATED by generate-resources.sh from manifests/kyverno-run-integrity.yaml, without matchConditions."
  awk '/^    matchConditions:$/{skip=1; next} skip && /^  rules:$/{skip=0} !skip' ../../manifests/kyverno-run-integrity.yaml
} > policy-under-test.yaml
