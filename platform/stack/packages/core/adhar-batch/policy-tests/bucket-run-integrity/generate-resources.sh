#!/usr/bin/env bash
# Regenerates the bucket run-integrity suite (design 0025 D26, §10.3): a run of a
# BatchJob that names a Bucket must match its template like any other, and the five
# ADHAR_S3_* variables (from <bucket>-bucket and <job>-s3) are as much the template's
# as the image: a run that reads another bucket, mounts the store's root credential
# directly, or drops the variables is refused.
#
# Inputs, written by TestBucketRunIntegrityFixtureIsTheComposedTemplate
# (platform/controllers/adharplatform, ADHAR_UPDATE_GOLDEN=1) from the composition's
# own render of testdata/batchjob/xr-ondemand.yaml with `bucket: reports`, never by hand:
#   run-template.json     the run template
#   job-as-admitted.json  that template as a kube-apiserver admits it (a server-side
#                         dry run on envtest: every default the policy must tolerate)
# The suite runs the shipped policy's CLI copy (../run-integrity/policy-under-test.yaml).
# Each variant changes one thing.
set -euo pipefail
cd "$(dirname "$0")"

{
  echo "# GENERATED by generate-resources.sh from run-template.json (the composed run template)."
  echo "apiVersion: cli.kyverno.io/v1alpha1"
  echo "kind: Values"
  echo "metadata:"
  echo "  name: bucket-run-integrity"
  echo "policies:"
  echo "  - name: adhar-batch-run-integrity"
  echo "    rules:"
  echo "      - name: a-run-matches-its-template"
  echo "        values:"
  echo "          templateYaml: $(jq -c . run-template.json | jq -Rs 'rtrimstr("\n")')"
} > values.yaml

C='.spec.template.spec.containers[0]'
variant() { # name, jq program
  jq -c --arg n "$1" "(.metadata.name=\$n) | ($2)" job-as-admitted.json
  echo "---"
}
secretof() { # env name, Secret  →  jq program pointing that variable at another Secret
  echo "(${C}.env[] | select(.name==\"$1\").valueFrom.secretKeyRef.name) = \"$2\""
}
{
  echo "# GENERATED by generate-resources.sh; each document is job-as-admitted.json with one change."
  # Runs a client may start.
  variant run-ok '.'
  variant run-with-params "(${C}.env[] | select(.name==\"ADHAR_BATCH_PARAMS\").value) = \"{\\\"businessDate\\\":\\\"2026-11-03\\\"}\""
  # Runs Kyverno must refuse.
  variant deny-other-bucket "$(secretof ADHAR_S3_BUCKET payroll-bucket)"
  variant deny-root-credential "$(secretof ADHAR_S3_SECRET_KEY root-creds)"
  variant deny-literal-endpoint "(${C}.env[] | select(.name==\"ADHAR_S3_ENDPOINT\")) |= {name:\"ADHAR_S3_ENDPOINT\",value:\"http://collector.example.com:9000\"}"
  variant deny-dropped-bucket "${C}.env |= map(select(.name | startswith(\"ADHAR_S3_\") | not))"
} > resources.yaml
