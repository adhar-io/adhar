#!/usr/bin/env bash
# Regenerates the two chunked run-integrity suites (design 0025 D11, §10.3): a
# `mode: chunked` run must match its template like any other, and the things only a
# chunked run carries — ADHAR_BATCH_DISTRIBUTION, the two Queue Secrets mounted by
# envFrom under their prefixes, the broker password, the OpenLineage variables — are
# as much the template's as the image.
#
# Inputs, written by TestChunkedRunIntegrityFixturesAreTheComposedTemplates
# (platform/controllers/adharplatform, ADHAR_UPDATE_GOLDEN=1) from the composition's
# own render of testdata/batchjob-chunked/xr-chunked.yaml, never by hand:
#   native/run-template.json   the Indexed Job template (no Volcano)
#   native/job-as-admitted.json  that template as a kube-apiserver admits it (a
#                              server-side dry run on envtest: every default the
#                              policy must tolerate is in it)
#   volcano/run-template.json  the gang template (Volcano)
# Both suites run the shipped policies' CLI copies (../run-integrity and
# ../volcano-run-integrity policy-under-test.yaml). Each variant changes one thing.
set -euo pipefail
cd "$(dirname "$0")"

values() { # suite, policy, rule
  echo "# GENERATED by ../generate-resources.sh from run-template.json (the composed run template)."
  echo "apiVersion: cli.kyverno.io/v1alpha1"
  echo "kind: Values"
  echo "metadata:"
  echo "  name: chunked-run-integrity-$1"
  echo "policies:"
  echo "  - name: $2"
  echo "    rules:"
  echo "      - name: $3"
  echo "        values:"
  echo "          templateYaml: $(jq -c . "$1/run-template.json" | jq -Rs 'rtrimstr("\n")')"
}

# ── native: the Indexed Job, as admitted ──
C='.spec.template.spec.containers[0]'
nvariant() { # name, jq program
  jq -c --arg n "$1" "(.metadata.name=\$n) | ($2)" native/job-as-admitted.json
  echo "---"
}
envset() { # container path, name, value  →  jq program setting that env entry's value
  echo "(${1}.env[] | select(.name==\"${2}\").value) = \"${3}\""
}
{
  echo "# GENERATED by ../generate-resources.sh; each document is job-as-admitted.json with one change."
  nvariant run-ok '.'
  nvariant run-with-params "$(envset "$C" ADHAR_BATCH_PARAMS '{\"businessDate\":\"2026-11-03\"}')"
  nvariant run-restart "$(envset "$C" ADHAR_BATCH_TRIGGER restart) | ${C}.env += [{name:\"ADHAR_BATCH_RESTART_OF\",value:\"ledger-09932cb3\"}] | .metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\""
  # A chunked run turned into another distribution, or given the partition channel.
  nvariant deny-distribution "$(envset "$C" ADHAR_BATCH_DISTRIBUTION partitioned)"
  nvariant deny-no-distribution "${C}.env |= map(select(.name!=\"ADHAR_BATCH_DISTRIBUTION\"))"
  nvariant deny-partition-channel "${C}.env += [{name:\"ADHAR_BATCH_PARTITION_TRANSPORT\",value:\"jdbc\"}]"
  # ADHAR_BATCH_MODE binds to adhar.batch.mode (auto|kubernetes|embedded); a chunked
  # run never carries it, and a run that adds it is not its template.
  nvariant deny-mode "${C}.env += [{name:\"ADHAR_BATCH_MODE\",value:\"embedded\"}]"
  nvariant deny-chunking-timeout "$(envset "$C" ADHAR_BATCH_CHUNKING_TIMEOUT 999999s)"
  # The broker: another team's Queue, a Secret without its prefix (its keys become
  # bare host/port/... variables), an extra Secret, another password.
  nvariant deny-request-queue "${C}.envFrom[0].secretRef.name=\"someone-elses-queue\""
  nvariant deny-reply-queue "${C}.envFrom[1].secretRef.name=\"someone-elses-queue\""
  nvariant deny-queue-prefix "del(${C}.envFrom[0].prefix)"
  nvariant deny-extra-envfrom "${C}.envFrom += [{secretRef:{name:\"root-creds\"}}]"
  nvariant deny-password-secret "(${C}.env[] | select(.name==\"ADHAR_BATCH_CHUNKING_PASSWORD\").valueFrom.secretKeyRef) = {name:\"root-creds\",key:\"rootPassword\"}"
  # Lineage sent somewhere else, under another namespace, with another token, or not at all.
  nvariant deny-lineage-receiver "$(envset "$C" OPENLINEAGE_URL http://collector.evil.example)"
  nvariant deny-lineage-namespace "$(envset "$C" OPENLINEAGE_NAMESPACE adhar/acme/other/shop/prod)"
  nvariant deny-lineage-token "(${C}.env[] | select(.name==\"OPENLINEAGE_API_KEY\").valueFrom.secretKeyRef.name) = \"someone-elses-token\""
  nvariant deny-lineage-key "(${C}.env[] | select(.name==\"OPENLINEAGE_API_KEY\").valueFrom.secretKeyRef.key) = \"admin-token\""
  nvariant deny-lineage-dropped "${C}.env |= map(select(.name!=\"OPENLINEAGE_URL\"))"
  # The shape is still the template's.
  nvariant deny-indexes ".spec.completions=10 | .spec.parallelism=10"
  nvariant deny-image "${C}.image=\"docker.io/library/busybox:1.36\""
} > native/resources.yaml
values native adhar-batch-run-integrity a-run-matches-its-template > native/values.yaml

# ── volcano: the gang, as Volcano's mutating webhook hands it on (tasks gain maxRetry 3) ──
M='.spec.tasks[0].template.spec.containers[0]'
W='.spec.tasks[1].template.spec.containers[0]'
ALL='.spec.tasks[].template.spec.containers[0]'
vvariant() { # name, jq program
  jq -c --arg n "$1" '.metadata.name=$n | .spec.tasks |= map(.maxRetry = (.maxRetry // 3))' volcano/run-template.json | jq -c "$2"
  echo "---"
}
{
  echo "# GENERATED by ../generate-resources.sh; each document is run-template.json as admitted, with one change."
  vvariant run-ok '.'
  vvariant run-with-params "$(envset "$ALL" ADHAR_BATCH_PARAMS '{\"businessDate\":\"2026-11-03\"}')"
  vvariant run-restart "$(envset "$ALL" ADHAR_BATCH_TRIGGER restart) | ${ALL}.env += [{name:\"ADHAR_BATCH_RESTART_OF\",value:\"ledger-09932cb3\"}] | .metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\" | .spec.tasks[].template.metadata.labels[\"adhar.io/batch-trigger\"]=\"restart\""
  vvariant deny-worker-distribution "$(envset "$W" ADHAR_BATCH_DISTRIBUTION partitioned)"
  vvariant deny-manager-distribution "$(envset "$M" ADHAR_BATCH_DISTRIBUTION partitioned)"
  vvariant deny-no-distribution "${W}.env |= map(select(.name!=\"ADHAR_BATCH_DISTRIBUTION\"))"
  vvariant deny-partition-channel "${W}.env += [{name:\"ADHAR_BATCH_PARTITION_TRANSPORT\",value:\"jdbc\"}]"
  vvariant deny-mode "${M}.env += [{name:\"ADHAR_BATCH_MODE\",value:\"embedded\"}]"
  vvariant deny-chunking-timeout "$(envset "$W" ADHAR_BATCH_CHUNKING_TIMEOUT 999999s)"
  vvariant deny-worker-request-queue "${W}.envFrom[0].secretRef.name=\"someone-elses-queue\""
  vvariant deny-manager-reply-queue "${M}.envFrom[1].secretRef.name=\"someone-elses-queue\""
  vvariant deny-queue-prefix "del(${W}.envFrom[0].prefix)"
  vvariant deny-extra-envfrom "${M}.envFrom += [{secretRef:{name:\"root-creds\"}}]"
  vvariant deny-password-secret "(${W}.env[] | select(.name==\"ADHAR_BATCH_CHUNKING_PASSWORD\").valueFrom.secretKeyRef) = {name:\"root-creds\",key:\"rootPassword\"}"
  vvariant deny-lineage-receiver "$(envset "$M" OPENLINEAGE_URL http://collector.evil.example)"
  vvariant deny-lineage-namespace "$(envset "$W" OPENLINEAGE_NAMESPACE adhar/acme/other/shop/prod)"
  vvariant deny-lineage-token "(${M}.env[] | select(.name==\"OPENLINEAGE_API_KEY\").valueFrom.secretKeyRef.name) = \"someone-elses-token\""
  vvariant deny-lineage-key "(${W}.env[] | select(.name==\"OPENLINEAGE_API_KEY\").valueFrom.secretKeyRef.key) = \"admin-token\""
  vvariant deny-lineage-dropped "${W}.env |= map(select(.name!=\"OPENLINEAGE_NAMESPACE\"))"
  vvariant deny-workers ".spec.tasks[1].replicas=8 | .spec.tasks[1].minAvailable=8 | .spec.minAvailable=9"
  vvariant deny-image "${W}.image=\"docker.io/library/busybox:1.36\""
} > volcano/resources.yaml
values volcano adhar-batch-run-integrity-volcano a-volcano-run-matches-its-template > volcano/values.yaml
