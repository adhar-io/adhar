#!/bin/bash
set -e

INSTALL_YAML="manifests/install.yaml"
# grafana/alloy 1.15.0 ships Alloy v1.21.3. The OpenTelemetry Engine (the
# otel-engine container) exists since Alloy v1.13 and is public preview since
# v1.21.0. Bump controller.extraContainers[otel-engine].image in values.yaml
# together with this: the render below refuses two different images.
CHART_VERSION="1.15.0"

helm repo add grafana https://grafana.github.io/helm-charts --force-update
helm repo update
helm template --namespace adhar-system alloy grafana/alloy -f values.yaml --version ${CHART_VERSION} >${INSTALL_YAML}

python3 - "${INSTALL_YAML}" "${CHART_VERSION}" <<'PYEOF'
import hashlib, sys, yaml
path, chart = sys.argv[1], sys.argv[2]
docs = [d for d in yaml.safe_load_all(open(path)) if d]

# The chart ships probes with timeoutSeconds: 1, which no package here may do
# (TestNoProbeShipsAOneSecondTimeout): a loaded node needs longer than a second
# to answer, and kubelet then kills a healthy agent. Raised on every render so a
# regeneration cannot silently revert it (it did, 2026-09-24).
raised = 0
for d in docs:
    if d.get("kind") not in ("Deployment", "StatefulSet", "DaemonSet"):
        continue
    spec = d["spec"]["template"]["spec"]
    for c in (spec.get("containers") or []) + (spec.get("initContainers") or []):
        for probe in ("livenessProbe", "readinessProbe", "startupProbe"):
            p = c.get(probe)
            if p and p.get("timeoutSeconds", 1) < 5:
                p["timeoutSeconds"] = 5; raised += 1
print(f"probes: {raised} timeout(s) raised to 5s")

# The OpenTelemetry Engine runs as the otel-engine container (values.yaml,
# controller.extraContainers) beside the default engine's alloy container.
pods = [d["spec"]["template"] for d in docs
        if d.get("kind") == "DaemonSet" and d["metadata"]["name"] == "alloy"]
if len(pods) != 1:
    sys.exit("expected exactly one alloy DaemonSet in the render")
pod = pods[0]
containers = {c["name"]: c for c in pod["spec"]["containers"]}
alloy, engine = containers.get("alloy"), containers.get("otel-engine")
if alloy is None or engine is None:
    sys.exit("the render has no alloy and otel-engine containers: values.yaml lost controller.extraContainers")
# One binary, two engines: a chart bump that moves the alloy container to a new
# release must move the engine with it.
if engine["image"] != alloy["image"]:
    sys.exit(f"otel-engine runs {engine['image']} but the chart's alloy container runs {alloy['image']}: "
             "update controller.extraContainers[otel-engine].image in values.yaml")
# The chart declares every alloy.extraPorts entry on the alloy container, but
# the OTLP ports are the engine's. Declare each port once, on the container
# that listens; the Service targets them by number either way.
owned = {(p["containerPort"], p.get("protocol", "TCP")) for p in engine.get("ports") or []}
kept = [p for p in alloy.get("ports") or [] if (p["containerPort"], p.get("protocol", "TCP")) not in owned]
print(f"ports: {len(alloy.get('ports') or []) - len(kept)} moved from alloy to otel-engine")
alloy["ports"] = kept
# The engine has no reload endpoint (the config-reloader only reaches the
# default engine), so a changed config must roll the pods.
cms = [d for d in docs if d.get("kind") == "ConfigMap" and d["metadata"]["name"] == "alloy-otel-engine"]
if len(cms) != 1 or "config.yaml" not in (cms[0].get("data") or {}):
    sys.exit("the render has no alloy-otel-engine ConfigMap with config.yaml: values.yaml lost extraObjects")
digest = hashlib.sha256(cms[0]["data"]["config.yaml"].encode()).hexdigest()
pod["metadata"].setdefault("annotations", {})["checksum/otel-engine-config"] = digest
print(f"otel-engine config sha256 {digest[:12]} stamped on the pod template")

# Multi-line strings as literal blocks, so the engine config reads as YAML in
# review. (config.alloy is indented with tabs, which a block scalar cannot
# carry: PyYAML keeps it double-quoted.)
class Dumper(yaml.SafeDumper):
    pass
def text(dumper, s):
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)
Dumper.add_representer(str, text)
with open(path, "w") as fh:
    fh.write(f"# Generated by generate-manifests.sh from values.yaml (grafana/alloy chart {chart}).\n"
             "# Do not edit: change values.yaml or the script, then regenerate.\n")
    yaml.dump_all(docs, fh, Dumper=Dumper, default_flow_style=False, sort_keys=False)
PYEOF

# Validate both engines' configurations with the exact image the DaemonSet
# runs. An unknown component, field or feature gate stops `alloy otel` before
# it serves one request, on every node at once; this is the cheap place to
# find out. Needs Docker; SKIP_ALLOY_VALIDATE=1 skips it.
if [ "${SKIP_ALLOY_VALIDATE:-}" = "1" ]; then
  echo "validate: skipped (SKIP_ALLOY_VALIDATE=1)"
elif ! docker info >/dev/null 2>&1; then
  echo "validate: Docker unavailable — run again with Docker before committing a version or config change" >&2
else
  WORK="$(mktemp -d)"
  trap 'rm -rf "${WORK}"' EXIT
  python3 - "${INSTALL_YAML}" "${WORK}" <<'PYEOF'
import os, sys, yaml
path, work = sys.argv[1], sys.argv[2]
docs = [d for d in yaml.safe_load_all(open(path)) if d]
cms = {d["metadata"]["name"]: d["data"] for d in docs if d.get("kind") == "ConfigMap"}
ds = next(d for d in docs if d.get("kind") == "DaemonSet" and d["metadata"]["name"] == "alloy")
engine = next(c for c in ds["spec"]["template"]["spec"]["containers"] if c["name"] == "otel-engine")
open(os.path.join(work, "config.alloy"), "w").write(cms["alloy"]["config.alloy"])
open(os.path.join(work, "config.yaml"), "w").write(cms["alloy-otel-engine"]["config.yaml"])
open(os.path.join(work, "image"), "w").write(engine["image"])
open(os.path.join(work, "gates"), "w").write("\n".join(a for a in engine["args"] if a.startswith("--feature-gates=")))
PYEOF
  IMAGE="$(cat "${WORK}/image")"
  HUB_ENV=(-e HUB_MIMIR_URL=http://mimir-gateway:8080/api/v1/push -e HUB_LOKI_URL=http://loki:3100/loki/api/v1/push
           -e HUB_TEMPO_URL=http://tempo:4318 -e HUB_CLUSTER_NAME=validate)
  # shellcheck disable=SC2046
  docker run --rm "${HUB_ENV[@]}" -v "${WORK}:/cfg:ro" "${IMAGE}" \
    otel validate --config=/cfg/config.yaml $(cat "${WORK}/gates")
  docker run --rm "${HUB_ENV[@]}" -v "${WORK}:/cfg:ro" "${IMAGE}" validate /cfg/config.alloy
  echo "validate: both engine configurations accepted by ${IMAGE}"
fi
