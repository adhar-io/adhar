#!/usr/bin/env python3
"""Build every Adhar Grafana dashboard filed in a folder (all of them except the
"Adhar Platform" front page, build-platform-dashboard.py, and the per-application
dashboards, hack/dashboards/build-app-dashboard.py).

    ./build-service-dashboards.py                   # build + write manifests/dashboard-<name>.yaml
    ./build-service-dashboards.py --check           # fail if any manifest is stale (CI)
    ./build-service-dashboards.py --refresh-mixins  # re-vendor the kubernetes-mixin first

A SMALL set per folder (dash_<folder>.py), each one a health-at-a-glance row on top
and one collapsible row per component below it. They replaced 120-odd community and
one-off dashboards on 2026-10-23: several views of the same thing (four Kubernetes
"compute" families, three Redis, three Kafka, five Loki, four Tempo, three Mimir), a
dozen for packages disabled in every profile, and many reading metrics this platform
does not export. dash_common.RETIRED maps each retired uid to its successor.

Building blocks:
  dashlib.py          panel primitives and the Dash layout (rows, sections, merge, embed)
  dash_common.py      uids, link bar, kubernetes-mixin loader, generic component sections
  dash_k8s_core.py    the cluster overview and capacity views (hand-authored)
  dash_data_core.py   CloudNativePG, Valkey, Kafka brokers + topics, RabbitMQ
  dash_<folder>.py    the dashboards of one Grafana folder (DASHBOARDS list)

The kubernetes-mixin is vendored from prometheus-operator/kube-prometheus under
dashboards-custom/kubernetes-mixin/ (its queries match the recording rules
kube-prometheus-stack installs) and embedded into the Kubernetes and Networking
dashboards with descriptions added and links redirected to the successors.
"""
import importlib.util
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True

import dash_ai  # noqa: E402
import dash_data  # noqa: E402
import dash_delivery  # noqa: E402
import dash_kubernetes  # noqa: E402
import dash_networking  # noqa: E402
import dash_observability  # noqa: E402
import dash_resilience  # noqa: E402
import dash_security  # noqa: E402

MANIFESTS = os.path.join(HERE, "manifests")
MIXIN = os.path.join(HERE, "dashboards-custom", "kubernetes-mixin")

MODULES = [dash_kubernetes, dash_networking, dash_data, dash_delivery, dash_security, dash_observability,
           dash_ai, dash_resilience]

# kubernetes-mixin files vendored by --refresh-mixins.
MIXINS = ["apiserver", "controller-manager", "scheduler", "kubelet", "k8s-resources-cluster",
          "k8s-resources-namespace", "k8s-resources-workloads-namespace", "k8s-resources-node",
          "k8s-resources-nodes-overview", "k8s-resources-pod", "k8s-resources-workload", "persistentvolumesusage",
          "node-cluster-rsrc-use", "cluster-total", "namespace-by-pod", "namespace-by-workload"]
MIXIN_URL = "https://raw.githubusercontent.com/prometheus-operator/kube-prometheus/main/manifests/grafana-dashboardDefinitions.yaml"

HEADER = ("# GENERATED by build-service-dashboards.py ({module}.py) — edit the generator, then re-run it.\n"
          "# ./build-service-dashboards.py --check fails CI when this file is stale.\n")


def _gen():
    spec = importlib.util.spec_from_file_location("gen", os.path.join(HERE, "generate-dashboards.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def all_dashboards():
    """(manifest name, folder, module name, dashboard JSON) for every dashboard built here."""
    out, uids = [], {}
    for mod in MODULES:
        for name, folder, fn in mod.DASHBOARDS:
            dash = fn().json()
            if dash["uid"] in uids:
                raise SystemExit(f"uid {dash['uid']} is used by both {uids[dash['uid']]} and {name}")
            uids[dash["uid"]] = name
            out.append((name, folder, mod.__name__, dash))
    return out


def render(name, folder, module, dash, gen):
    return HEADER.format(module=module) + gen.configmap_yaml(name, folder, dash)


def refresh_mixins():
    import yaml  # only needed when refreshing
    req = urllib.request.Request(MIXIN_URL, headers={"User-Agent": "adhar-dashboards"})
    with urllib.request.urlopen(req, timeout=60) as r:
        docs = yaml.safe_load(r.read().decode())
    os.makedirs(MIXIN, exist_ok=True)
    for item in docs["items"]:
        for key, body in item["data"].items():
            if key[:-5] in MIXINS:
                with open(os.path.join(MIXIN, key), "w") as f:
                    json.dump(json.loads(body), f, indent=1, sort_keys=True)
                print("vendored", key)


def main():
    if "--refresh-mixins" in sys.argv:
        refresh_mixins()
    gen = _gen()
    stale = []
    for name, folder, module, dash in all_dashboards():
        path = os.path.join(MANIFESTS, f"dashboard-{name}.yaml")
        text = render(name, folder, module, dash, gen)
        if "--check" in sys.argv:
            try:
                current = open(path).read()
            except FileNotFoundError:
                current = None
            if current != text:
                stale.append(path)
            continue
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {folder:13} {name:28} {dash['title']}")
    if stale:
        sys.exit("stale dashboards (run build-service-dashboards.py):\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
