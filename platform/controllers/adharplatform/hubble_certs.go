// Hubble's TLS material, issued per cluster.
//
// The embedded install manifest used to ship both Secrets pre-generated by
// Helm for the management cluster: `hubble-server-certs` with the SAN
// `*.adhar-mgmt.hubble-grpc.cilium.io`. Since Cilium 1.20 hubble-relay learns
// each agent's TLS server name from the hubble-peer service, which derives it
// from the AGENT's cluster-name (`<node>.<cluster>.hubble-grpc.cilium.io`). On
// every cluster not called adhar-mgmt the agents therefore presented a
// certificate for a name nobody asked for, the relay dropped every peer after
// the handshake ("No connection to peer"), went NOT_SERVING and was restarted
// by its liveness probe — the console's "Data streams are reconnecting".
// Measured on `adhar-prod` (2026-10-24).
const (
	hubbleServerCertSecret = "hubble-server-certs"
	hubbleRelayCertSecret  = "hubble-relay-client-certs"
	hubbleRelayConfigMap   = "hubble-relay-config"
	hubbleRelayDeployment  = "hubble-relay"

	// hubbleRelayClientName is Cilium certgen's (and the Helm chart's) fixed
	// identity for the relay's client certificate. The agents verify only the
	// chain, not the name, but keeping the convention keeps `cilium hubble`
	// tooling and any future name check happy.
	hubbleRelayClientName = "*.hubble-relay.cilium.io"

	// hubblePKIAnnotation is stamped on the relay's pod template with a digest
	// of the TLS material and relay config it runs with. It changes exactly
	// when the relay's identity does, which is when it must restart.
	hubblePKIAnnotation = "adhar.io/hubble-pki"

	// hubblePKIFieldOwner is deliberately NOT v1alpha1.FieldManager: the relay
	// Deployment is applied by that manager from install.yaml, which does not
	// carry the annotation, and a shared manager would strip it on the next
	// apply and roll the relay again.
	hubblePKIFieldOwner = "adhar-hubble-pki"
)

// hubbleCertSecrets are the Secrets ensureHubbleCerts owns; the rendered
// copies are dropped from the applied manifest so a reconcile can never put
// the management cluster's certificate back.
var hubbleCertSecrets = []string{hubbleServerCertSecret, hubbleRelayCertSecret}

// hubbleServerName is the wildcard every agent's Hubble server certificate
// must carry for the given Cilium cluster name.
func hubbleServerName(clusterName string) string {
	return "*." + clusterName + ".hubble-grpc.cilium.io"
}

// ensureHubbleCerts issues the Hubble server and relay client certificates
// from the cluster's own `cilium-ca`. A certificate is reissued only when it
// is missing, not signed by the current CA, carries the wrong name, lacks the
// required key usage, or is within a month of expiry — so a steady-state
// reconcile changes nothing. It reports whether anything was (re)issued.
//
// The agents and the relay watch the mounted certificate files (Cilium's
// certloader) and reload them once kubelet refreshes the projected volume, so
// no agent restart is needed; the relay is rolled by reconcileHubbleTLS
// because its cluster-name is read only at start-up.
func (r *AdharPlatformReconciler) ensureHubbleCerts(ctx context.Context, clusterName string) (bool, error) {
	logger := log.FromContext(ctx)

	caSecret := &corev1.Secret{}
	if err := r.Get(ctx, types.NamespacedName{Name: "cilium-ca", Namespace: globals.AdharSystemNamespace}, caSecret); err != nil {
		return false, fmt.Errorf("reading cilium-ca: %w", err)
	}
	caCert, caKey, err := parseCA(caSecret.Data["ca.crt"], caSecret.Data["ca.key"])
	if err != nil {
		return false, err
	}
	caPEM := caSecret.Data["ca.crt"]

	serverName := hubbleServerName(clusterName)
	specs := []struct {
		secret string
		cn     string
		server bool
	}{
		{secret: hubbleServerCertSecret, cn: serverName, server: true},
		{secret: hubbleRelayCertSecret, cn: hubbleRelayClientName},
	}

	issued := false
	for _, spec := range specs {
		existing := &corev1.Secret{}
		err := r.Get(ctx, types.NamespacedName{Name: spec.secret, Namespace: globals.AdharSystemNamespace}, existing)
		if err != nil && !apierrors.IsNotFound(err) {
			return issued, fmt.Errorf("reading %s: %w", spec.secret, err)
		}
		if err == nil && hubbleCertStillValid(existing, caCert, caPEM, spec.cn, spec.server) {
			continue
		}
		crtPEM, keyPEM, err := issueCert(caCert, caKey, spec.cn, []string{spec.cn}, nil, spec.server)
		if err != nil {
			return issued, fmt.Errorf("issuing %s: %w", spec.secret, err)
		}
		secret := &corev1.Secret{
			TypeMeta: metav1.TypeMeta{APIVersion: "v1", Kind: "Secret"},
			ObjectMeta: metav1.ObjectMeta{
				Name:      spec.secret,
				Namespace: globals.AdharSystemNamespace,
				Labels: map[string]string{
					"adhar.io/component":        "hubble",
					"adhar.io/issued-by":        "adhar-operator",
					"app.kubernetes.io/part-of": "cilium",
				},
				Annotations: map[string]string{
					// Not in any Git source: an Argo app that ever shares the
					// namespace must neither flag nor prune it.
					"argocd.argoproj.io/compare-options": "IgnoreExtraneous",
					"argocd.argoproj.io/sync-options":    "Prune=false",
				},
			},
			Type: corev1.SecretTypeTLS,
			Data: map[string][]byte{"tls.crt": crtPEM, "tls.key": keyPEM, "ca.crt": caPEM},
		}
		if err := r.Patch(ctx, secret, client.Apply,
			client.FieldOwner(v1alpha1.FieldManager), client.ForceOwnership); err != nil {
			return issued, fmt.Errorf("applying %s: %w", spec.secret, err)
		}
		issued = true
		logger.Info("Issued Hubble certificate from cilium-ca", "secret", spec.secret, "commonName", spec.cn)
	}
	return issued, nil
}

// hubbleCertStillValid is certStillValid plus what Hubble additionally relies
// on: the SAN (TLS verification ignores the CN), the extended key usage, and
// the bundled ca.crt being the current CA (the agents use it as the client CA,
// the relay as the server CA).
func hubbleCertStillValid(secret *corev1.Secret, ca *x509.Certificate, caPEM []byte, name string, server bool) bool {
	if !certStillValid(secret, ca, name) {
		return false
	}
	if !bytes.Equal(bytes.TrimSpace(secret.Data["ca.crt"]), bytes.TrimSpace(caPEM)) {
		return false
	}
	if len(secret.Data["tls.key"]) == 0 {
		return false
	}
	block, _ := pem.Decode(secret.Data["tls.crt"])
	cert, err := x509.ParseCertificate(block.Bytes) // certStillValid already parsed it
	if err != nil {
		return false
	}
	if !slices.Contains(cert.DNSNames, name) {
		return false
	}
	usage := x509.ExtKeyUsageClientAuth
	if server {
		usage = x509.ExtKeyUsageServerAuth
	}
	return slices.Contains(cert.ExtKeyUsage, usage)
}

// relayClusterNameLine is the cluster-name key of hubble-relay-config's
// config.yaml (unquoted, at the start of a line).
var relayClusterNameLine = regexp.MustCompile(`(?m)^cluster-name: .*$`)

// reconcileHubbleTLS keeps the platform's own Hubble consistent with the
// cluster's Cilium identity: certificates issued for the real cluster name,
// the relay configured with the same name, and the relay restarted when either
// changes. It does nothing on a cluster whose Cilium the platform did not
// install (no `cilium-ca` in the platform namespace).
//
// It runs both from ReconcileCilium (so `adhar upgrade` converges it) and on
// every steady-state reconcile, because the foundation installers stop running
// once the platform is up.
func (r *AdharPlatformReconciler) reconcileHubbleTLS(ctx context.Context, resource *v1alpha1.AdharPlatform) error {
	ca := &corev1.Secret{}
	if err := r.Get(ctx, types.NamespacedName{Name: "cilium-ca", Namespace: globals.AdharSystemNamespace}, ca); err != nil {
		if apierrors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("reading cilium-ca: %w", err)
	}
	name, _ := ClusterMeshIdentity(resource)
	if _, err := r.ensureHubbleCerts(ctx, name); err != nil {
		return err
	}
	if err := r.alignHubbleRelayClusterName(ctx, name); err != nil {
		return err
	}
	return r.rollHubbleRelayOnPKIChange(ctx)
}

// alignHubbleRelayClusterName rewrites hubble-relay-config's cluster-name when
// it disagrees with the cluster's. ReconcileCilium already applies the right
// value; this covers a controller upgraded without the foundation being
// re-applied, where the relay would otherwise dial the hubble-peer service as
// `hubble-peer.adhar-mgmt.hubble-grpc.cilium.io` against a certificate that is
// now (correctly) issued for the real name.
func (r *AdharPlatformReconciler) alignHubbleRelayClusterName(ctx context.Context, clusterName string) error {
	cm := &corev1.ConfigMap{}
	if err := r.Get(ctx, types.NamespacedName{Name: hubbleRelayConfigMap, Namespace: globals.AdharSystemNamespace}, cm); err != nil {
		if apierrors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("reading %s: %w", hubbleRelayConfigMap, err)
	}
	current := cm.Data["config.yaml"]
	want := "cluster-name: " + clusterName
	if !relayClusterNameLine.MatchString(current) {
		return nil
	}
	updated := relayClusterNameLine.ReplaceAllLiteralString(current, want)
	if updated == current {
		return nil
	}
	cm.Data["config.yaml"] = updated
	if err := r.Update(ctx, cm, client.FieldOwner(hubblePKIFieldOwner)); err != nil {
		return fmt.Errorf("updating %s: %w", hubbleRelayConfigMap, err)
	}
	log.FromContext(ctx).Info("Aligned hubble-relay cluster-name with Cilium", "clusterName", clusterName)
	return nil
}

// rollHubbleRelayOnPKIChange restarts hubble-relay when the TLS material or
// relay configuration it should run with differs from what its pods were
// started with. The relay reloads certificate FILES on its own, but its
// cluster-name — the name it expects on the hubble-peer service — is read once
// at start-up. The agents are never restarted: they reload the server
// certificate from the mounted files, and restarting the CNI is not a cost a
// certificate rotation should pay.
func (r *AdharPlatformReconciler) rollHubbleRelayOnPKIChange(ctx context.Context) error {
	digest, err := r.hubblePKIDigest(ctx)
	if err != nil || digest == "" {
		return err
	}
	deploy := &appsv1.Deployment{}
	if err := r.Get(ctx, types.NamespacedName{Name: hubbleRelayDeployment, Namespace: globals.AdharSystemNamespace}, deploy); err != nil {
		if apierrors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("reading Deployment %s: %w", hubbleRelayDeployment, err)
	}
	if deploy.Spec.Template.Annotations[hubblePKIAnnotation] == digest {
		return nil
	}
	if deploy.Spec.Template.Annotations == nil {
		deploy.Spec.Template.Annotations = map[string]string{}
	}
	deploy.Spec.Template.Annotations[hubblePKIAnnotation] = digest
	if err := r.Update(ctx, deploy, client.FieldOwner(hubblePKIFieldOwner)); err != nil {
		return fmt.Errorf("restarting Deployment %s: %w", hubbleRelayDeployment, err)
	}
	log.FromContext(ctx).Info("Restarted hubble-relay for new Hubble TLS identity", "digest", digest)
	return nil
}

// hubblePKIDigest fingerprints the two certificates and the relay config.
// Empty (no error) when any of them is not there yet.
func (r *AdharPlatformReconciler) hubblePKIDigest(ctx context.Context) (string, error) {
	h := sha256.New()
	for _, name := range hubbleCertSecrets {
		s := &corev1.Secret{}
		if err := r.Get(ctx, types.NamespacedName{Name: name, Namespace: globals.AdharSystemNamespace}, s); err != nil {
			if apierrors.IsNotFound(err) {
				return "", nil
			}
			return "", fmt.Errorf("reading %s: %w", name, err)
		}
		h.Write(s.Data["tls.crt"])
		h.Write(s.Data["ca.crt"])
	}
	cm := &corev1.ConfigMap{}
	if err := r.Get(ctx, types.NamespacedName{Name: hubbleRelayConfigMap, Namespace: globals.AdharSystemNamespace}, cm); err != nil {
		if apierrors.IsNotFound(err) {
			return "", nil
		}
		return "", fmt.Errorf("reading %s: %w", hubbleRelayConfigMap, err)
	}
	h.Write([]byte(cm.Data["config.yaml"]))
	return hex.EncodeToString(h.Sum(nil))[:16], nil
}

// stripHubbleCertSecrets removes the rendered Hubble TLS Secrets from the
// install manifest so the per-cluster certificates issued by ensureHubbleCerts
// are not overwritten with the management cluster's on every apply.
func stripHubbleCertSecrets(manifest []byte) []byte {
	return stripSecretDocs(manifest, hubbleCertSecrets)
}
