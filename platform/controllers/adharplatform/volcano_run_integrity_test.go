package adharplatform

// The Volcano half of run integrity (FU-8, design 0025 §10.3): a Volcano Job that
// claims a BatchJob must be that BatchJob's composed run template, as a batch/v1 Job
// must be under the native policy. The policy itself is proven by the kyverno CLI
// (`make policy-test`, policy-tests/volcano-run-integrity/: every field a client may
// and may not change); these hold its fixtures to what the composition and the
// manifest actually are, and its outage alert to its webhook name. Each guard was
// mutation-tested (the behaviour reverted, the test seen failing, restored).

import (
	"encoding/json"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	sigsyaml "sigs.k8s.io/yaml"
)

func volcanoIntegrityDir(t *testing.T) string {
	return filepath.Join(queuePolicyDir(t), "policy-tests", "volcano-run-integrity")
}

// canonicalJSON reads YAML or JSON into its sorted-key JSON form.
func canonicalJSON(t *testing.T, what string, raw []byte) string {
	t.Helper()
	var v any
	if err := sigsyaml.Unmarshal(raw, &v); err != nil {
		t.Fatalf("%s does not parse: %v", what, err)
	}
	b, _ := json.Marshal(v)
	return string(b)
}

// The CLI suite's template is the composition's own run template for the design's
// partitioned example, so the suite proves the policy against what a real BatchJob
// composes, not against a hand-written guess of it.
func TestVolcanoRunIntegrityFixtureIsTheComposedTemplate(t *testing.T) {
	var composed string
	for _, d := range vcMustRender(t, vcXR(t, "xr-partitioned.yaml"), vcCluster(t), nil) {
		if dig(d, "metadata", "annotations", "gotemplating.fn.crossplane.io/composition-resource-name") == "run-template" {
			if dig(d, "data", "kind") != "VolcanoJob" {
				t.Fatalf("xr-partitioned.yaml with Volcano composes a %v run template, not a VolcanoJob", dig(d, "data", "kind"))
			}
			composed, _ = dig(d, "data", "template.yaml").(string)
		}
	}
	if composed == "" {
		t.Fatal("xr-partitioned.yaml composes no run template")
	}
	fixture, err := os.ReadFile(filepath.Join(volcanoIntegrityDir(t), "run-template.json"))
	if err != nil {
		t.Fatal(err)
	}
	if canonicalJSON(t, "run-template.json", fixture) != canonicalJSON(t, "the composed template.yaml", []byte(composed)) {
		t.Error("policy-tests/volcano-run-integrity/run-template.json is not the run template the composition renders for xr-partitioned.yaml; copy it from golden-volcano-gang.yaml and run generate-resources.sh")
	}
	// values.yaml (what the CLI hands the policy as the ConfigMap's template.yaml) is
	// generated from that file.
	for file, transform := range map[string]func(string) string{
		"values.yaml": func(s string) string { return s },
		"pinned-template/values.yaml": func(s string) string {
			return regexp.MustCompile(`("image":"[^"@]+)"`).ReplaceAllString(s, `$1@sha256:1111111111111111111111111111111111111111111111111111111111111111"`)
		},
	} {
		docs := readYAMLDocs(t, filepath.Join(volcanoIntegrityDir(t), file))
		got, _ := dig(docs[0], "policies").([]any)
		var tpl string
		if len(got) == 1 {
			rules, _ := got[0].(map[string]any)["rules"].([]any)
			if len(rules) == 1 {
				tpl, _ = dig(rules[0].(map[string]any), "values", "templateYaml").(string)
			}
		}
		if want := transform(canonicalJSON(t, "run-template.json", fixture)); canonicalJSON(t, file, []byte(tpl)) != want {
			t.Errorf("policy-tests/volcano-run-integrity/%s does not hand the policy run-template.json; run generate-resources.sh", file)
		}
	}
}

// The kyverno CLI cannot load matchConditions (it panics), so the suite loads a copy
// without them: the copy must be the shipped policies in everything else.
func TestVolcanoRunIntegrityFixtureIsTheShippedPolicy(t *testing.T) {
	shipped, err := os.ReadFile(filepath.Join(queuePolicyDir(t), "manifests", "volcano", "kyverno-run-integrity.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"# GENERATED by generate-resources.sh from manifests/volcano/kyverno-run-integrity.yaml, without matchConditions."}
	skip := false
	for _, line := range strings.Split(strings.TrimSuffix(string(shipped), "\n"), "\n") {
		switch {
		case line == "    matchConditions:":
			skip = true
			continue
		case skip && line == "  rules:":
			skip = false
		}
		if !skip {
			want = append(want, line)
		}
	}
	got, err := os.ReadFile(filepath.Join(volcanoIntegrityDir(t), "policy-under-test.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.TrimSuffix(string(got), "\n") != strings.Join(want, "\n") {
		t.Error("policy-tests/volcano-run-integrity/policy-under-test.yaml is not the shipped policy without matchConditions; run its generate-resources.sh")
	}
	if strings.Contains(string(got), "\n    matchConditions:") {
		t.Error("the CLI copy still carries matchConditions")
	}
	if strings.Count(string(shipped), "\n    matchConditions:") != 1 {
		t.Error("manifests/volcano/kyverno-run-integrity.yaml: the fail-closed policy needs its matchConditions, and only it")
	}
}

// The policy must name the Volcano Job kind, and only on CREATE, and it must live in
// manifests/volcano/: Kyverno refuses a policy naming a kind the cluster does not
// serve, and manifests/ syncs everywhere.
func TestVolcanoRunIntegrityCoversVolcanoRunsOnly(t *testing.T) {
	var policy map[string]any
	for _, doc := range readYAMLDocs(t, filepath.Join(queuePolicyDir(t), "manifests", "volcano", "kyverno-run-integrity.yaml")) {
		if toString(metaName(doc)) == "adhar-batch-run-integrity-volcano" {
			policy = doc
		}
	}
	if policy == nil {
		t.Fatal("manifests/volcano/kyverno-run-integrity.yaml ships no adhar-batch-run-integrity-volcano")
	}
	rules := toSlice(dig(policy, "spec", "rules"))
	if len(rules) != 1 {
		t.Fatalf("adhar-batch-run-integrity-volcano has %d rules, want 1", len(rules))
	}
	rule := rules[0].(map[string]any)
	filters := toSlice(dig(rule, "match", "any"))
	if len(filters) != 1 {
		t.Fatalf("the rule matches %d resource filters", len(filters))
	}
	kinds := tqJSON(dig(filters[0].(map[string]any), "resources", "kinds"))
	ops := tqJSON(dig(filters[0].(map[string]any), "resources", "operations"))
	if kinds != `["batch.volcano.sh/v1alpha1/Job"]` || ops != `["CREATE"]` {
		t.Errorf("adhar-batch-run-integrity-volcano matches %s on %s; want the Volcano Job on CREATE", kinds, ops)
	}
	if dig(rule, "validate", "failureAction") != "Enforce" {
		t.Errorf("adhar-batch-run-integrity-volcano is %v, not Enforce", dig(rule, "validate", "failureAction"))
	}
}

// Each fail-closed policy has a webhook of its own (a policy with matchConditions is
// registered fine-grained), and the fail-open alert must count every one of them, or
// an override back to Ignore admits that kind of run unchecked and reads exactly like
// a quiet week.
func TestEveryFailClosedPolicyHasAFailOpenAlert(t *testing.T) {
	matcher := regexp.MustCompile(`apiserver_admission_webhook_fail_open_count\{[^}]*name=~"([^"]+)"`)
	var patterns []string
	for _, doc := range yamlDocs(t, filepath.Join(queuePolicyDir(t), "manifests", "alerts.yaml")) {
		for _, g := range toSlice(dig(doc, "spec", "groups")) {
			for _, r := range toSlice(g.(map[string]any)["rules"]) {
				if m := matcher.FindStringSubmatch(toString(r.(map[string]any)["expr"])); m != nil {
					patterns = append(patterns, strings.ReplaceAll(m[1], `\\`, `\`))
				}
			}
		}
	}
	if len(patterns) == 0 {
		t.Fatal("core/adhar-batch alerts.yaml has no fail-open alert")
	}
	for _, name := range failClosedNames() {
		for _, failure := range []string{"ignore", "fail"} {
			webhook := "validate.kyverno.svc-" + failure + "-finegrained-" + name
			seen := false
			for _, p := range patterns {
				seen = seen || regexp.MustCompile("^(?:"+p+")$").MatchString(webhook)
			}
			if !seen {
				t.Errorf("no fail-open alert counts webhook %s, which Kyverno registers for the fail-closed policy %s", webhook, name)
			}
		}
	}
}
